// Writes src/lib/githubHeaderFonts.ts: the two fonts the live GitHub header needs, cut down to the
// characters it can show and embedded as base64 WOFF2, plus the metrics used to place baselines.
// The site itself needs no font tooling at run time, and no new dependency.
//
// Usage (outside the site's dependencies; subset-font is only needed here):
//   mkdir ghcard && cd ghcard && npm init -y && npm i subset-font@2.4.0
//   put Instrument-Serif.ttf and IBM-Plex-Mono.ttf (Google Fonts, SIL Open Font License 1.1) in ghcard/fonts/
//   node <this file> <portfolio-root>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(join(process.cwd(), "package.json"));
const subsetFont = require("subset-font");
const [root] = process.argv.slice(2);

const SERIF_TEXT = "Muhammed Favas0123456789:";
let ascii = "";
for (let c = 32; c < 127; c++) ascii += String.fromCharCode(c);
const MONO_TEXT = ascii + "·";

function metrics(ttf) {
  const n = ttf.readUInt16BE(4);
  const table = (tag) => {
    for (let i = 0; i < n; i++) {
      const o = 12 + i * 16;
      if (ttf.toString("latin1", o, o + 4) === tag) return ttf.readUInt32BE(o + 8);
    }
    throw new Error(`no ${tag} table`);
  };
  const hhea = table("hhea");
  return { upm: ttf.readUInt16BE(table("head") + 18), asc: ttf.readInt16BE(hhea + 4), desc: ttf.readInt16BE(hhea + 6) };
}

const serifTtf = readFileSync(join(process.cwd(), "fonts/Instrument-Serif.ttf"));
const monoTtf = readFileSync(join(process.cwd(), "fonts/IBM-Plex-Mono.ttf"));
const serif = await subsetFont(serifTtf, SERIF_TEXT, { targetFormat: "woff2" });
const mono = await subsetFont(monoTtf, MONO_TEXT, { targetFormat: "woff2" });

const file = `/* Generated by docs/github-profile/make-header-fonts.mjs. Do not edit by hand.
 * Subsets of Instrument Serif and IBM Plex Mono (both SIL Open Font License 1.1), embedded in the
 * live GitHub header so it renders in the site's type with no outside requests.
 * Serif: ${JSON.stringify(SERIF_TEXT)}. Mono: printable ASCII and "·".
 */

export const SERIF = {
  woff2: "${serif.toString("base64")}",
  ...${JSON.stringify(metrics(serifTtf))},
};

export const MONO = {
  woff2: "${mono.toString("base64")}",
  ...${JSON.stringify(metrics(monoTtf))},
};
`;
writeFileSync(join(root, "src/lib/githubHeaderFonts.ts"), file);
console.log(`serif ${(serif.length / 1024).toFixed(1)} KB, mono ${(mono.length / 1024).toFixed(1)} KB`);
